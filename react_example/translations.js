/**
 * Get translation string for a given key and language
 * @param {string} key - Translation key
 * @param {string} language - Language code ('en', 'hi', 'mr')
 * @returns {string} Translated string
 */
export const getTranslation = (key, language = 'en') => {
  const lang = TRANSLATIONS[language] || TRANSLATIONS.en;
  return lang[key] || TRANSLATIONS.en[key] || key;
};

/**
 * Get all translation strings for a language
 * @param {string} language - Language code ('en', 'hi', 'mr')
 * @returns {object} Translation strings object
 */
export const getTranslationStrings = (language = 'en') => {
  return TRANSLATIONS[language] || TRANSLATIONS.en;
};

/**
 * Detect language from browser
 * @returns {string} Detected language code
 */
export const detectBrowserLanguage = () => {
  const browserLang = navigator.language.split('-')[0];
  return TRANSLATIONS[browserLang] ? browserLang : 'en';
};

export default TRANSLATIONS;
